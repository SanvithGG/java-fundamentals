package Arithmetic;

public class circle {
    public static void main(String[] args) {
        int radius = 30;

        double area;
        double curcumference;
        double diameter;
        area = 3.1415 * radius * radius;
        System.out.println(area);

        curcumference = 2 * 3.1415 * radius * radius;
        System.out.println(curcumference);

        diameter = 2 * radius;
        System.out.println(diameter);
    }
}

